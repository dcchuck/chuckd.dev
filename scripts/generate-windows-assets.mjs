/**
 * Regenerates the Windows Classic theme's artwork: the sprite sheet, cursors, and bitmap fonts.
 * Run with `npm run windows:assets` after changing anything in scripts/windows-assets/.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { buildFonts } from './windows-assets/font.mjs';
import { buildCursors, buildSprites, encodePng, packSheet } from './windows-assets/sprite.mjs';

const root = new URL('../', import.meta.url);
const publicDir = new URL('public/windows/', root);
await mkdir(publicDir, { recursive: true });

const { sheet, placed } = packSheet(buildSprites());
await writeFile(new URL('icons.png', publicDir), encodePng(sheet));

const names = Object.keys(placed).sort();
const css = [
  '/* Generated by scripts/generate-windows-assets.mjs. Do not edit by hand. */',
  "html[data-theme='windows-classic'] {",
  ...names.map(name => `  --sp-${name}:${-placed[name].x}px ${-placed[name].y}px;`),
  '  #skin-experience {',
  ...names.map(name => `    .i-${name} { width:${placed[name].w}px; height:${placed[name].h}px; --sp:var(--sp-${name}); }`),
  '  }',
  '}',
  '',
].join('\n');
await writeFile(new URL('src/styles/windows-sprite.css', root), css);
await writeFile(new URL('src/components/windows/sprite-names.json', root), `${JSON.stringify(names)}\n`);

for (const [name, data] of Object.entries(buildFonts())) await writeFile(new URL(name, publicDir), data);
for (const [name, data] of Object.entries(buildCursors())) await writeFile(new URL(name, publicDir), data);

console.log(`Wrote ${names.length} sprites (${sheet.w}x${sheet.h}), cursors, and fonts.`);
